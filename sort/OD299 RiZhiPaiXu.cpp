// OD299 日志排序
// 题目描述：
// 运维工程师采集到某产品线网运行一天产生的日志 n 条，现需根据日志时间先后顺序对日志进行排序，日志时间格式为 H: M: S.N。
// - H 表示小时 (0~23)
// - M 表示分钟 (0~59)
// - S 表示秒 (0~59)
// - N 表示毫秒 (0~999)
// 时间可能并没有补全，也就是说，01:01:01.001 也可能表示为 1:1:1.1。
// 输入描述 ：
// 第一行输入一个整数 n 表示日志条数，1 <= n <= 100000，接下来 n 行输入 n 个时间。
// 输出描述：
// 按时间升序排序之后的时间，如果有两个时间表示的时间相同，则保持输入顺序。
// 用例 1：
// 输入：
// ```
// 2
// 01:41:8.9
// 1:1:09.211
// ```
// 输出：
// ```
// 1:1:09.211
// 01:41:8.9
// ```
// 用例 2：
// 输入：
// ```
// 3
// 23:41:08.023
// 1:1:09.211
// 08:01:22.0
// ```
// 输出：
// ```
// 1:1:09.211
// 08:01:22.0
// 23:41:08.023
// ```
// 用例 3：
// 输入：
// ```
// 2
// 22:41:08.023
// 22:41:08.23
// ```
// 输出：
// ```
// 22:41:08.023
// 22:41:08.23
// ```
// 说明：两个时间表示的时间相同，保持输入顺序
// 难度：中等
// 标签：字符串、排序

#include <bits/stdc++.h>

using namespace std;

int main() {
  int n;
  cin >> n;
  vector<string> logs(n);
  for (int i = 0; i < n; i++) {
    cin >> logs[i];
  }

  ranges::stable_sort(logs, [](const auto& a, const auto& b) {
    int h1, h2, m1, m2, s1, s2, n1, n2;
    sscanf(a.c_str(), "%d:%d:%d.%d", &h1, &m1, &s1, &n1);
    sscanf(b.c_str(), "%d:%d:%d.%d", &h2, &m2, &s2, &n2);

    // 直接分别比较时分秒毫秒，避免计算后数据过大
    if (h1 != h2) return h1 < h2;
    if (m1 != m2) return m1 < m2;
    if (s1 != s2) return s1 < s2;
    return n1 < n2;
  });

  for (const auto& log : logs) {
    cout << log << endl;
  }

  return 0;
}